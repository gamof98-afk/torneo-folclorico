-- Esquema inicial del Torneo folclórico.
-- Ejecuta en Supabase SQL Editor. Revisa las políticas antes de publicar.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'viewer' check (role in ('admin','viewer')),
  created_at timestamptz not null default now()
);
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  short_name text,
  created_at timestamptz not null default now()
);
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  round_name text,
  match_date date,
  home_team_id bigint references public.teams(id) on delete set null,
  away_team_id bigint references public.teams(id) on delete set null,
  home_score integer check (home_score is null or home_score >= 0),
  away_score integer check (away_score is null or away_score >= 0),
  status text not null default 'scheduled' check (status in ('scheduled','played','postponed')),
  notes text,
  created_at timestamptz not null default now(),
  check (home_team_id is null or away_team_id is null or home_team_id <> away_team_id)
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  published boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.resolutions (
  id bigint generated by default as identity primary key,
  resolution_number text not null unique,
  title text not null,
  body text not null,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.teams enable row level security;
alter table public.matches enable row level security;
alter table public.announcements enable row level security;
alter table public.resolutions enable row level security;

create or replace function public.is_tournament_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin') $$;

create policy "Profiles: user reads own profile" on public.profiles for select to authenticated using (id = auth.uid() or public.is_tournament_admin());
create policy "Teams public read" on public.teams for select to anon, authenticated using (true);
create policy "Teams admin insert" on public.teams for insert to authenticated with check (public.is_tournament_admin());
create policy "Teams admin update" on public.teams for update to authenticated using (public.is_tournament_admin()) with check (public.is_tournament_admin());
create policy "Teams admin delete" on public.teams for delete to authenticated using (public.is_tournament_admin());
create policy "Matches public read" on public.matches for select to anon, authenticated using (true);
create policy "Matches admin insert" on public.matches for insert to authenticated with check (public.is_tournament_admin());
create policy "Matches admin update" on public.matches for update to authenticated using (public.is_tournament_admin()) with check (public.is_tournament_admin());
create policy "Matches admin delete" on public.matches for delete to authenticated using (public.is_tournament_admin());
create policy "Announcements published read" on public.announcements for select to anon, authenticated using (published = true or public.is_tournament_admin());
create policy "Announcements admin write" on public.announcements for all to authenticated using (public.is_tournament_admin()) with check (public.is_tournament_admin());
create policy "Resolutions published read" on public.resolutions for select to anon, authenticated using (published = true or public.is_tournament_admin());
create policy "Resolutions admin write" on public.resolutions for all to authenticated using (public.is_tournament_admin()) with check (public.is_tournament_admin());

